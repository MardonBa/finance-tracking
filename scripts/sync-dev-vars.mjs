#!/usr/bin/env node
// Writes apps/api/.dev.vars (local `wrangler dev` secrets) and
// apps/desktop/.env.development.local from the root .env. Both are gitignored.
// Only Sandbox/dev values are ever copied: production secrets are set with
// `wrangler secret put --env production` and never live in these files.
//
//   node scripts/sync-dev-vars.mjs              write the local files
//   node scripts/sync-dev-vars.mjs --deployed   also push the same secrets to the
//                                                deployed dev Worker (wrangler secret bulk --env dev)
import { spawnSync } from "node:child_process";
import { join } from "node:path";
import { ROOT, readEnvFile, writeEnvFile } from "./lib/env-file.mjs";
import { genSecrets } from "./gen-secrets.mjs";

genSecrets({ quiet: true });
const env = readEnvFile();

const required = ["PLAID_CLIENT_ID", "PLAID_SANDBOX_SECRET", "TOKEN_ENC_KEY", "BACKUP_ENC_KEY", "APP_TOKEN_PEPPER"];
const missing = required.filter((k) => !env[k]);
if (missing.length) {
  console.error(`Missing in .env: ${missing.join(", ")} (see .env.example)`);
  process.exit(1);
}

const devVars = {
  PLAID_CLIENT_ID: env.PLAID_CLIENT_ID,
  PLAID_SECRET: env.PLAID_SANDBOX_SECRET, // dev always uses the Sandbox secret
  PLAID_ENV: "sandbox",
  GOOGLE_CLIENT_ID: env.GOOGLE_CLIENT_ID ?? "",
  GOOGLE_CLIENT_SECRET: env.GOOGLE_CLIENT_SECRET ?? "",
  GEMINI_API_KEY: env.GEMINI_API_KEY ?? "",
  ALLOWED_GOOGLE_SUB: env.ALLOWED_GOOGLE_SUB ?? "",
  ALLOWED_GOOGLE_EMAIL: env.ALLOWED_GOOGLE_EMAIL ?? "",
  TOKEN_ENC_KEY: env.TOKEN_ENC_KEY,
  BACKUP_ENC_KEY: env.BACKUP_ENC_KEY,
  APP_TOKEN_PEPPER: env.APP_TOKEN_PEPPER,
  // Honoured by the Worker only when ENVIRONMENT is "dev" (src/auth.ts).
  DEV_APP_TOKEN: env.DEV_APP_TOKEN ?? "",
};

for (const [k, v] of Object.entries(devVars)) {
  if (/prod/i.test(k) || /prod/i.test(String(v).slice(0, 8))) {
    console.error(`Refusing to copy ${k}: looks like a production value`);
    process.exit(1);
  }
}

// Dev only talks to Plaid Sandbox. Catch a non-Sandbox secret (e.g. the production one) here,
// instead of as an "Internal error" when a bank is connected. Offline: warn and carry on.
async function checkSandboxKeys() {
  const call = (host) =>
    fetch(`https://${host}.plaid.com/institutions/get`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ client_id: env.PLAID_CLIENT_ID, secret: env.PLAID_SANDBOX_SECRET, count: 1, offset: 0, country_codes: ["US"] }),
      signal: AbortSignal.timeout(5000),
    }).then(async (r) => ({ ok: r.ok, code: (await r.json().catch(() => ({}))).error_code }));
  try {
    const sandbox = await call("sandbox");
    if (sandbox.ok) return;
    if (sandbox.code !== "INVALID_API_KEYS") return console.warn(`Plaid Sandbox check: ${sandbox.code ?? "unexpected response"} (continuing)`);
    const production = await call("production").catch(() => ({ ok: false }));
    console.error(
      production.ok
        ? "PLAID_SANDBOX_SECRET in .env is your PRODUCTION secret. Local dev only uses Plaid Sandbox: put the Sandbox secret back (Plaid dashboard → Developers → Keys). Real banks are connected through the production app (docs/shipping.md)."
        : "Plaid rejected PLAID_CLIENT_ID / PLAID_SANDBOX_SECRET from .env for Sandbox. Copy them again from the Plaid dashboard → Developers → Keys.",
    );
    process.exit(1);
  } catch {
    console.warn("Plaid Sandbox check skipped (no network)");
  }
}
await checkSandboxKeys();

writeEnvFile(join(ROOT, "apps/api/.dev.vars"), devVars, "Generated by scripts/sync-dev-vars.mjs from the root .env. Do not edit or commit.");
writeEnvFile(
  join(ROOT, "apps/desktop/.env.development.local"),
  { VITE_API_URL: "http://localhost:8787", VITE_DEV_APP_TOKEN: env.DEV_APP_TOKEN ?? "" },
  "Generated by scripts/sync-dev-vars.mjs. Dev-only bearer token for the local API. Do not commit.",
);
console.log(`Wrote apps/api/.dev.vars (${Object.keys(devVars).length} keys) and apps/desktop/.env.development.local`);

if (process.argv.includes("--deployed")) {
  const secrets = Object.fromEntries(Object.entries(devVars).filter(([k, v]) => k !== "PLAID_ENV" && v !== ""));
  const res = spawnSync("npx", ["wrangler", "secret", "bulk", "--env", "dev"], {
    cwd: join(ROOT, "apps/api"),
    input: JSON.stringify(secrets),
    stdio: ["pipe", "inherit", "inherit"],
  });
  if (res.status !== 0) process.exit(res.status ?? 1);
  console.log(`Pushed ${Object.keys(secrets).length} secrets to the deployed dev Worker`);
}
