/**
 * Writes the deterministic dev seed as SQL.
 *   node --experimental-strip-types seed/build-seed-sql.ts <out.sql> [--today YYYY-MM-DD]
 * Reads TOKEN_ENC_KEY, APP_TOKEN_PEPPER and DEV_APP_TOKEN from the
 * environment (scripts/reset-dev.mjs passes them from .dev.vars / .env).
 */
import { writeFileSync } from "node:fs";
import { DATA_KEYS, isIsoDate, isoDateInTimeZone } from "@ft/core";
import { TABLES } from "../src/db/tables.ts";
import { appCredentials, plaidItems } from "../src/db/schema.ts";
import { encryptString } from "../src/crypto/aes.ts";
import { hashAppToken } from "../src/auth.ts";
import { buildDevSeed } from "./dev-seed.ts";
import { insertSql } from "./sql.ts";

const [out] = process.argv.slice(2).filter((a) => !a.startsWith("--") && !isIsoDate(a));
const todayArg = process.argv[process.argv.indexOf("--today") + 1];
if (!out) throw new Error("usage: build-seed-sql.ts <out.sql> [--today YYYY-MM-DD]");
const today = process.argv.includes("--today") && isIsoDate(todayArg) ? todayArg : isoDateInTimeZone(Date.now(), process.env.USER_TIME_ZONE ?? "America/New_York");

const env = (k: string) => {
  const v = process.env[k];
  if (!v) throw new Error(`${k} is not set (run npm run sync:dev-vars)`);
  return v;
};

const data = buildDevSeed(today);
const statements: string[] = [];

// Items carry backend-only columns. The seed bank is not a real Plaid item, so
// its "token" is a marker that sync code must skip (prefix "seed-").
for (const item of data.items) {
  statements.push(
    ...insertSql(plaidItems, [{ ...item, accessTokenEnc: await encryptString("seed-not-a-plaid-token", env("TOKEN_ENC_KEY")), transactionsCursor: null }]),
  );
}
for (const key of DATA_KEYS) {
  if (key === "items") continue;
  statements.push(...insertSql(TABLES[key] as never, data[key] as object[]));
}
statements.push(
  ...insertSql(appCredentials, [
    {
      id: "cred_dev",
      tokenHash: await hashAppToken(env("DEV_APP_TOKEN"), env("APP_TOKEN_PEPPER")),
      label: "Local dev (DEV_APP_TOKEN)",
      createdAt: `${today}T00:00:00.000Z`,
      expiresAt: null,
      lastUsedAt: null,
      revokedAt: null,
    },
  ]),
);

writeFileSync(out, `-- Generated by seed/build-seed-sql.ts for today=${today}. Do not edit.\n${statements.join("\n")}\n`);
console.log(`Seed for ${today}: ${data.transactions.length} transactions, ${data.accounts.length} accounts → ${out}`);
